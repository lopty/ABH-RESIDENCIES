// Scans public/projects/<slug>/ and writes src/seo/projects/imageManifest.ts so the
// portal picks up new project images automatically. Run: npx tsx scripts/build-image-manifest.ts
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..", "public", "projects");
const out = path.join(__dirname, "..", "src", "seo", "projects", "imageManifest.ts");

const manifest: Record<string, string[]> = {};
if (fs.existsSync(root)) {
  for (const slug of fs.readdirSync(root).sort()) {
    const dir = path.join(root, slug);
    if (!fs.statSync(dir).isDirectory()) continue;
    const files = fs
      .readdirSync(dir)
      .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
    if (files.length) manifest[slug] = files.map((f) => `/projects/${slug}/${f}`);
  }
}

fs.writeFileSync(
  out,
  `// Generated by scripts/build-image-manifest.ts. Do not edit by hand.\nexport const imageManifest: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};\n`
);
console.log(`[image-manifest] ${Object.keys(manifest).length} projects with images`);
